class DarshanGalleryController {
  constructor() {
    this.currentList = [];
    this.currentIndex = 0;
    this.activeFilter = 'All';
  }

  renderRadhaGovind(filter = 'All') {
    this.activeFilter = filter;
    const container = document.getElementById('radhaGovindGrid');
    if (!container) return;

    let items = RADHA_GOVIND_IMAGES;
    if (filter !== 'All') {
      items = RADHA_GOVIND_IMAGES.filter(img => img.tag === filter);
    }

    container.innerHTML = items.map((img, index) => {
      const encodedPath = `images/radha-govind/${encodeURIComponent(img.file)}`;
      return `
        <div class="darshan-card" onclick="gallery.openGalleryLightbox('radha-govind', ${index}, '${filter}')">
          <div class="darshan-img-frame">
            <img src="${encodedPath}" alt="${img.title}" class="darshan-img" loading="lazy" onerror="this.onerror=null; this.src='https://images.unsplash.com/photo-1545128485-c400e7702796?auto=format&fit=crop&w=600&q=80';">
            <span class="darshan-tag-badge">${img.tag}</span>
          </div>
          <div class="darshan-info">
            <div class="darshan-caption">🦚 ${img.title}</div>
            <div class="darshan-sub">Sri Sri Radha Govind Ji • Sri Vrindavan Dham</div>
          </div>
        </div>
      `;
    }).join('');
  }

  renderRadhaMadhav(filter = 'All') {
    this.activeFilter = filter;
    const container = document.getElementById('radhaMadhavGrid');
    if (!container) return;

    let items = RADHA_MADHAV_IMAGES;
    if (filter !== 'All') {
      items = RADHA_MADHAV_IMAGES.filter(img => img.tag === filter);
    }

    container.innerHTML = items.map((img, index) => {
      const encodedPath = `images/radha-madhav/${encodeURIComponent(img.file)}`;
      return `
        <div class="darshan-card" onclick="gallery.openGalleryLightbox('radha-madhav', ${index}, '${filter}')">
          <div class="darshan-img-frame">
            <img src="${encodedPath}" alt="${img.title}" class="darshan-img" loading="lazy" onerror="this.onerror=null; this.src='https://images.unsplash.com/photo-1609137144813-7d9921338f24?auto=format&fit=crop&w=600&q=80';">
            <span class="darshan-tag-badge">${img.tag}</span>
          </div>
          <div class="darshan-info">
            <div class="darshan-caption">🌸 ${img.title}</div>
            <div class="darshan-sub">Sri Sri Radha Madhav • Sri Mayapur Dham</div>
          </div>
        </div>
      `;
    }).join('');
  }

  openGalleryLightbox(category, index, filter = 'All') {
    const rawList = category === 'radha-govind' ? RADHA_GOVIND_IMAGES : RADHA_MADHAV_IMAGES;
    const basePath = category === 'radha-govind' ? 'images/radha-govind' : 'images/radha-madhav';
    
    this.currentList = filter === 'All' ? rawList : rawList.filter(img => img.tag === filter);
    this.currentIndex = index;
    this.basePath = basePath;

    this.showLightboxItem();
    const modal = document.getElementById('lightboxModal');
    if (modal) modal.classList.add('active');

    if (window.soundEngine) window.soundEngine.playBlessingSparkle();
  }

  showLightboxItem() {
    const item = this.currentList[this.currentIndex];
    if (!item) return;

    const img = document.getElementById('lightboxImage');
    const cap = document.getElementById('lightboxCaptionText');
    const counter = document.getElementById('lightboxCounterText');

    const encodedPath = `${this.basePath}/${encodeURIComponent(item.file)}`;
    if (img) img.src = encodedPath;
    if (cap) cap.innerHTML = `<strong>${item.title}</strong><br><span style="font-size:0.85rem; color:var(--gold-bright);">🪷 ${item.tag} Darshan</span>`;
    if (counter) counter.textContent = `${this.currentIndex + 1} / ${this.currentList.length}`;
  }

  nextLightbox() {
    this.currentIndex = (this.currentIndex + 1) % this.currentList.length;
    this.showLightboxItem();
  }

  prevLightbox() {
    this.currentIndex = (this.currentIndex - 1 + this.currentList.length) % this.currentList.length;
    this.showLightboxItem();
  }
}

window.gallery = new DarshanGalleryController();
